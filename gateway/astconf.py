"""Generate the *_gen.conf files that the shipped Asterisk configs #include.

Everything the web UI manages ends up in these files:
  pjsip_gen.conf       transports + one endpoint/auth/aor per extension
  extensions_gen.conf  internal dialing, outbound routes, per-trunk inbound contexts
  rtp_gen.conf         ICE / STUN / TURN
  dongle_gen.conf      chan_dongle devices (Huawei USB modems)
  quectel_gen.conf     chan_quectel devices (Quectel / SimCom modules)
  mobile_gen.conf      chan_mobile adapter + Bluetooth phones
"""
import logging
import os
import re
import tempfile

log = logging.getLogger("astconf")

TECH_PREFIX = {"dongle": "Dongle", "quectel": "Quectel", "mobile": "Mobile"}
SAFE_NAME = re.compile(r"^[A-Za-z0-9_]{1,24}$")
SAFE_EXT = re.compile(r"^[0-9]{2,8}$")


def valid_name(n: str) -> bool:
    return bool(SAFE_NAME.match(n or ""))


def valid_ext(e: str) -> bool:
    return bool(SAFE_EXT.match(e or ""))


def _write_atomic(path: str, content: str):
    d = os.path.dirname(path)
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".gen-")
    with os.fdopen(fd, "w") as f:
        f.write(content)
    os.replace(tmp, path)
    try:
        os.chmod(path, 0o640)
    except OSError:
        pass


def _q(s: str) -> str:
    """Strip characters that would break a config line."""
    return re.sub(r"[\r\n;\[\]]", "", str(s or ""))


# ----------------------------------------------------------------- pjsip
def gen_pjsip(extensions, settings):
    ext_addr = _q(settings.get("external_address", "")).strip()
    local_net = _q(settings.get("local_net", "")).strip()
    nat = ""
    if ext_addr:
        nat += f"external_media_address={ext_addr}\nexternal_signaling_address={ext_addr}\n"
    for net in [n.strip() for n in local_net.split(",") if n.strip()]:
        nat += f"local_net={net}\n"

    out = [";; GENERATED by pi-sip-gateway. Do not edit; use the web UI.\n",
           "[transport-udp]\ntype=transport\nprotocol=udp\nbind=0.0.0.0:5060\nallow_reload=yes\n" + nat,
           "[transport-tcp]\ntype=transport\nprotocol=tcp\nbind=0.0.0.0:5060\nallow_reload=yes\n" + nat,
           "[transport-ws]\ntype=transport\nprotocol=ws\nbind=0.0.0.0\nallow_reload=yes\n" + nat,
           "[ep-common](!)\ntype=endpoint\ncontext=from-internal\ndisallow=all\nallow=ulaw\nallow=alaw\nallow=gsm\n"
           "direct_media=no\nrtp_symmetric=yes\nforce_rport=yes\nrewrite_contact=yes\nsend_pai=yes\n"
           "language=en\ndtmf_mode=rfc4733\ntos_audio=ef\ncos_audio=5\n",
           "[ep-sip](!,ep-common)\n",
           "[ep-web](!,ep-common)\nwebrtc=yes\ndtls_auto_generate_cert=yes\n",
           "[auth-common](!)\ntype=auth\nauth_type=userpass\n",
           "[aor-common](!)\ntype=aor\nmax_contacts=5\nremove_existing=no\nqualify_frequency=60\n"]
    for e in extensions:
        ext, name, secret = e["ext"], _q(e["name"]) or e["ext"], _q(e["secret"])
        out.append(f'[{ext}](ep-sip)\nauth={ext}\naors={ext}\ncallerid="{name}" <{ext}>\n')
        out.append(f"[{ext}](auth-common)\nusername={ext}\npassword={secret}\n")
        out.append(f"[{ext}](aor-common)\n")
        if e.get("webrtc"):
            w = f"{ext}-web"
            out.append(f'[{w}](ep-web)\nauth={w}\naors={w}\ncallerid="{name}" <{ext}>\n')
            out.append(f"[{w}](auth-common)\nusername={w}\npassword={secret}\n")
            out.append(f"[{w}](aor-common)\n")
    return "\n".join(out)


# ------------------------------------------------------------ dialplan
def _ext_dial(e, timeout=30):
    parts = [f"PJSIP/{e['ext']}"]
    if e.get("webrtc"):
        parts.append(f"PJSIP/{e['ext']}-web")
    return f"Dial({'&'.join(parts)},{timeout})"


def _trunk_dial(trunk, number_var="${DIALNUM}", timeout=60):
    tech = TECH_PREFIX.get(trunk["tech"], "Dongle")
    return f"Dial({tech}/{trunk['name']}/{number_var},{timeout})"


def gen_dialplan(extensions, trunks, outbound, inbound):
    by_name = {t["name"]: t for t in trunks if t.get("enabled", 1)}
    ext_map = {e["ext"]: e for e in extensions}
    all_ext_dial = "&".join(
        [f"PJSIP/{e['ext']}" + (f"&PJSIP/{e['ext']}-web" if e.get("webrtc") else "") for e in extensions]
    )
    L = [";; GENERATED by pi-sip-gateway. Do not edit; use the web UI.\n"]

    # internal extensions ------------------------------------------------
    L.append("[internal-ext]")
    for e in extensions:
        L.append(f"exten => {e['ext']},1,NoOp(Internal call to {e['ext']})")
        L.append(f" same => n,{_ext_dial(e)}")
        L.append(" same => n,Hangup()")
    L.append("exten => *43,1,Answer()\n same => n,Playback(demo-echotest)\n same => n,Echo()\n same => n,Hangup()")
    L.append("exten => *65,1,Answer()\n same => n,SayDigits(${CALLERID(num)})\n same => n,Hangup()")
    L.append("")

    # outbound routes ----------------------------------------------------
    L.append("[outbound-routes]")
    for r in outbound:
        if not r.get("enabled", 1):
            continue
        pat = _q(r["pattern"]).strip()
        if not pat:
            continue
        strip = int(r.get("strip") or 0)
        prepend = _q(r.get("prepend") or "")
        ordered = [by_name[n] for n in r.get("trunks", []) if n in by_name]
        if not ordered:
            continue
        label = _q(r.get("label") or pat)
        L.append(f"exten => {pat},1,NoOp(Outbound route '{label}' for ${{EXTEN}})")
        L.append(f" same => n,Set(DIALNUM={prepend}${{EXTEN:{strip}}})")
        L.append(" same => n,Set(CDR(userfield)=route:" + label + ")")
        for t in ordered:
            L.append(f" same => n,NoOp(Trying trunk {t['name']})")
            L.append(f" same => n,{_trunk_dial(t)}")
            L.append(' same => n,GotoIf($["${DIALSTATUS}" = "ANSWER" | "${DIALSTATUS}" = "BUSY" | '
                     '"${DIALSTATUS}" = "NOANSWER" | "${DIALSTATUS}" = "CANCEL"]?done)')
        L.append(" same => n,Playback(all-circuits-busy-now)")
        L.append(" same => n(done),Hangup()")
    L.append("")

    # inbound: one context per trunk ------------------------------------
    inb = {r["trunk"]: r for r in inbound}
    for t in trunks:
        name = t["name"]
        ctx = f"from-trunk-{name}"
        L.append(f"[{ctx}]")
        L.append(f"exten => s,1,Goto(inbound-{name},s,1)")
        L.append(f"exten => _X.,1,Goto(inbound-{name},s,1)")
        L.append(f"exten => _+X.,1,Goto(inbound-{name},s,1)")
        L.append(f"exten => sms,1,UserEvent(SMSIn,Trunk: {name},From: ${{CALLERID(num)}},Body64: ${{SMS_BASE64}})")
        L.append(" same => n,Hangup()")
        L.append("exten => ussd,1,Hangup()")
        L.append("exten => report,1,Hangup()")
        L.append("")
        L.append(f"[inbound-{name}]")
        L.append(f"exten => s,1,NoOp(Inbound call on {name} from ${{CALLERID(num)}})")
        L.append(f" same => n,Set(CDR(userfield)=trunk:{name})")
        r = inb.get(name)
        if r and r.get("enabled", 1) and r.get("destinations"):
            dests = [ext_map[x] for x in r["destinations"] if x in ext_map]
            dial = "&".join([f"PJSIP/{e['ext']}" + (f"&PJSIP/{e['ext']}-web" if e.get("webrtc") else "") for e in dests])
            ring = int(r.get("ring_time") or 30)
        else:
            dial, ring = all_ext_dial, 30
        if dial:
            L.append(f" same => n,Dial({dial},{ring})")
        else:
            L.append(" same => n,NoOp(No extensions configured)")
        L.append(" same => n,Hangup()")
        L.append("")

    # fallback for devices that are not configured in the UI
    L.append("[from-trunk-unknown]")
    L.append("exten => s,1,NoOp(Inbound from unconfigured device)")
    if all_ext_dial:
        L.append(f" same => n,Dial({all_ext_dial},30)")
    L.append(" same => n,Hangup()")
    L.append("exten => _X.,1,Goto(s,1)")
    L.append("exten => _+X.,1,Goto(s,1)")
    L.append("exten => sms,1,UserEvent(SMSIn,Trunk: unknown,From: ${CALLERID(num)},Body64: ${SMS_BASE64})")
    L.append(" same => n,Hangup()")
    return "\n".join(L) + "\n"


# ----------------------------------------------------------------- rtp
def gen_rtp(settings):
    L = [";; GENERATED by pi-sip-gateway",
         "rtpstart=10000", "rtpend=20000", "icesupport=yes", "strictrtp=yes"]
    stun = _q(settings.get("stun", "stun.l.google.com:19302")).strip()
    if stun:
        L.append(f"stunaddr={stun}")
    if settings.get("turn_mode", "none") != "none" and settings.get("turn_host"):
        L.append(f"turnaddr={_q(settings['turn_host'])}:{_q(settings.get('turn_port', '3478'))}")
        L.append(f"turnusername={_q(settings.get('turn_user', ''))}")
        L.append(f"turnpassword={_q(settings.get('turn_pass', ''))}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------ modems
def gen_dongle(trunks):
    L = [";; GENERATED by pi-sip-gateway"]
    for t in trunks:
        if t["tech"] != "dongle" or not t.get("enabled", 1):
            continue
        c = t["config"]
        L.append(f"[{t['name']}]")
        L.append(f"context=from-trunk-{t['name']}")
        L.append("group=1")
        if c.get("imei"):
            L.append(f"imei={_q(c['imei'])}")
        if c.get("imsi"):
            L.append(f"imsi={_q(c['imsi'])}")
        if c.get("audio") and c.get("data"):
            L.append(f"audio={_q(c['audio'])}")
            L.append(f"data={_q(c['data'])}")
        if c.get("rxgain"):
            L.append(f"rxgain={int(c['rxgain'])}")
        if c.get("txgain"):
            L.append(f"txgain={int(c['txgain'])}")
        L.append("")
    return "\n".join(L) + "\n"


