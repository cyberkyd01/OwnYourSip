def gen_mobile(trunks, settings):
    adapter = _q(settings.get("bt_adapter", "")).strip()
    L = [";; GENERATED by pi-sip-gateway"]
    phones = [t for t in trunks if t["tech"] == "mobile" and t.get("enabled", 1)]
    if adapter and phones:
        L.append("[adapter]")
        L.append("id=blue")
        L.append(f"address={adapter}")
        L.append("")
    for t in phones:
        c = t["config"]
        if not c.get("address"):
            continue
        L.append(f"[{t['name']}]")
        L.append(f"address={_q(c['address'])}")
        L.append(f"port={int(c.get('port') or 1)}")
        L.append(f"context=from-trunk-{t['name']}")
        L.append("adapter=blue")
        L.append("group=1")
        L.append("sms=yes")
        L.append("")
    return "\n".join(L) + "\n"


# --------------------------------------------------------------- apply
class ConfigWriter:
    def __init__(self, conf_dir: str):
        self.dir = conf_dir

    def write_all(self, db):
        exts = db.extensions()
        trunks = db.trunks()
        s = db.all_settings()
        files = {
            "pjsip_gen.conf": gen_pjsip(exts, s),
            "extensions_gen.conf": gen_dialplan(exts, trunks, db.outbound_routes(), db.inbound_routes()),
            "rtp_gen.conf": gen_rtp(s),
            "dongle_gen.conf": gen_dongle(trunks),
            "quectel_gen.conf": gen_quectel(trunks),
            "mobile_gen.conf": gen_mobile(trunks, s),
        }
        changed = []
        for name, content in files.items():
            path = os.path.join(self.dir, name)
            try:
                with open(path) as f:
                    if f.read() == content:
                        continue
            except FileNotFoundError:
                pass
            _write_atomic(path, content)
            changed.append(name)
        log.info("config written: %s", changed or "no changes")
        return changed


